/**
 * lib/minipdf.js
 * ─────────────────────────────────────────────────────────────────────────────
 * A tiny, dependency-free PDF writer good enough for operational reports
 * (title, meta line, and a paginated table). Uses the built-in Helvetica
 * fonts so no font files ship with the app.
 *
 * Only WinAnsi-safe characters are emitted; anything else is transliterated
 * (e.g. "₦" becomes "NGN "), which keeps every viewer happy.
 */

const PAGE = { w: 842, h: 595, margin: 36 }; // A4 landscape — reports are wide

function sanitize(text) {
  return String(text == null ? '' : text)
    .replace(/₦/g, 'NGN ')
    .replace(/[€£]/g, m => ({ '€': 'EUR ', '£': 'GBP ' }[m]))
    .replace(/[^\x20-\x7E]/g, '')
    .replace(/([()\\])/g, '\\$1');
}

/** Rough Helvetica width so columns can be truncated instead of overlapping. */
function textWidth(text, size) {
  return String(text).length * size * 0.5;
}

function fit(text, size, maxWidth) {
  let t = String(text == null ? '' : text);
  while (t.length > 1 && textWidth(t, size) > maxWidth) t = t.slice(0, -2) + '…';
  return t.replace(/…/g, '..');
}

/**
 * buildTablePdf({ title, subtitle, columns:[{header,width,key}], rows:[{}] })
 * → Buffer
 */
function buildTablePdf({ title, subtitle, columns, rows }) {
  const usable = PAGE.w - PAGE.margin * 2;
  const totalW = columns.reduce((a, c) => a + (c.width || 1), 0);
  const cols = columns.map(c => ({ ...c, px: ((c.width || 1) / totalW) * usable }));

  const bodySize = 8;
  const lineH = 14;
  const headerBlock = 74;
  const rowsPerPage = Math.floor((PAGE.h - PAGE.margin - headerBlock - 24) / lineH);
  const pages = [];
  for (let i = 0; i < Math.max(rows.length, 1); i += rowsPerPage) pages.push(rows.slice(i, i + rowsPerPage));

  const streams = pages.map((pageRows, pageIndex) => {
    const out = [];
    let y = PAGE.h - PAGE.margin;

    out.push('BT /F2 16 Tf 1 0 0 1 ' + PAGE.margin + ' ' + (y - 12) + ' Tm (' + sanitize(title) + ') Tj ET');
    y -= 30;
    out.push('BT /F1 9 Tf 1 0 0 1 ' + PAGE.margin + ' ' + (y - 8) + ' Tm (' + sanitize(subtitle) + ') Tj ET');
    y -= 24;

    // header row background
    out.push('0.92 0.94 0.98 rg ' + PAGE.margin + ' ' + (y - 4) + ' ' + usable + ' 16 re f 0 0 0 rg');
    let x = PAGE.margin + 3;
    for (const c of cols) {
      out.push('BT /F2 8 Tf 1 0 0 1 ' + x + ' ' + y + ' Tm (' + sanitize(fit(c.header, 8, c.px - 6)) + ') Tj ET');
      x += c.px;
    }
    y -= lineH + 2;

    for (const row of pageRows) {
      x = PAGE.margin + 3;
      for (const c of cols) {
        const cell = fit(row[c.key], bodySize, c.px - 6);
        out.push('BT /F1 ' + bodySize + ' Tf 1 0 0 1 ' + x + ' ' + y + ' Tm (' + sanitize(cell) + ') Tj ET');
        x += c.px;
      }
      out.push('0.88 0.88 0.9 RG 0.4 w ' + PAGE.margin + ' ' + (y - 4) + ' m ' + (PAGE.w - PAGE.margin) + ' ' + (y - 4) + ' l S');
      y -= lineH;
    }

    out.push('BT /F1 7 Tf 1 0 0 1 ' + PAGE.margin + ' ' + (PAGE.margin - 12) + ' Tm (Page ' +
      (pageIndex + 1) + ' of ' + pages.length + ' - generated by King Social Hub) Tj ET');
    return out.join('\n');
  });

  // ── assemble the PDF objects ───────────────────────────────────────────────
  const objects = [];
  const pageIds = streams.map((_, i) => 5 + i * 2);
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[2] = '<< /Type /Pages /Kids [' + pageIds.map(id => id + ' 0 R').join(' ') + '] /Count ' + pageIds.length + ' >>';
  objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>';
  objects[4] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>';
  streams.forEach((s, i) => {
    const pageId = pageIds[i];
    objects[pageId] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ' + PAGE.w + ' ' + PAGE.h +
      '] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ' + (pageId + 1) + ' 0 R >>';
    objects[pageId + 1] = '<< /Length ' + Buffer.byteLength(s, 'latin1') + ' >>\nstream\n' + s + '\nendstream';
  });

  let pdf = '%PDF-1.4\n';
  const offsets = [];
  for (let i = 1; i < objects.length; i++) {
    if (!objects[i]) continue;
    offsets[i] = Buffer.byteLength(pdf, 'latin1');
    pdf += i + ' 0 obj\n' + objects[i] + '\nendobj\n';
  }
  const xrefAt = Buffer.byteLength(pdf, 'latin1');
  const max = objects.length;
  pdf += 'xref\n0 ' + max + '\n0000000000 65535 f \n';
  for (let i = 1; i < max; i++) {
    pdf += offsets[i] ? String(offsets[i]).padStart(10, '0') + ' 00000 n \n' : '0000000000 65535 f \n';
  }
  pdf += 'trailer\n<< /Size ' + max + ' /Root 1 0 R >>\nstartxref\n' + xrefAt + '\n%%EOF';
  return Buffer.from(pdf, 'latin1');
}

module.exports = { buildTablePdf };
